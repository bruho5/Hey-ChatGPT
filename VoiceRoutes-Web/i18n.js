export function translate(lang,key,...args) {
 if(typeof key!=='string')return '';
 if(lang==='en'&&args.length===0){
   const m=/^第 (\d+) (.+)$/u.exec(key);
   if(m){
     const reason=rowErrors[m[2]]??rowErrors[m[2].replace(/^条/,'')];
     if(reason)return reason.replace('{0}',m[1]);
   }
 }
 const msg=lang==='en'?(en[key]??key):key;
 return msg.replace(/\{(\d+)\}/g,(match,i)=>args[i]??match);
}
